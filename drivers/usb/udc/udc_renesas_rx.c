struct udc_renesas_rx_config {
	const struct pinctrl_dev_config *pcfg;
	const struct device **clocks;
	size_t num_of_clocks;
	size_t num_of_eps;
	struct udc_ep_config *ep_cfg_in;
	struct udc_ep_config *ep_cfg_out;
	void (*make_thread)(const struct device *dev);
	int speed_idx;
};

struct udc_renesas_rx_data {
	struct k_thread thread_data;
	struct st_usbd_instance_ctrl udc;
	struct st_usbd_cfg udc_cfg;
};

enum udc_renesas_rx_event_type {
	/* An event generated by the HAL driver */
	UDC_RENESAS_RX_EVT_HAL,
	/* Shim driver event to trigger next transfer */
	UDC_RENESAS_RX_EVT_XFER,
	/* Let controller perform status stage */
	UDC_RENESAS_RX_EVT_STATUS,
};

struct udc_renesas_rx_evt {
	enum udc_renesas_rx_event_type type;
	usbd_event_t hal_evt;
	uint8_t ep;
};

K_MSGQ_DEFINE(drv_msgq, sizeof(struct udc_renesas_rx_evt), CONFIG_UDC_RENESAS_RX_MAX_QMESSAGES,
	      sizeof(uint32_t));

static void udc_renesas_rx_event_handler(usbd_callback_arg_t *p_args)
{
	const struct device *dev = p_args->p_context;
	struct udc_renesas_rx_evt evt;

	switch (p_args->event.event_id) {
	case USBD_EVENT_BUS_RESET:
		udc_submit_event(dev, UDC_EVT_RESET, 0);
		break;

	case USBD_EVENT_VBUS_RDY:
		udc_submit_event(dev, UDC_EVT_VBUS_READY, 0);
		break;

	case USBD_EVENT_VBUS_REMOVED:
		udc_submit_event(dev, UDC_EVT_VBUS_REMOVED, 0);
		break;

	case USBD_EVENT_SUSPEND:
		udc_set_suspended(dev, true);
		udc_submit_event(dev, UDC_EVT_SUSPEND, 0);
		break;

	case USBD_EVENT_RESUME:
		udc_set_suspended(dev, false);
		udc_submit_event(dev, UDC_EVT_RESUME, 0);
		break;

	case USBD_EVENT_SOF:
		udc_submit_sof_event(dev);
		break;

	default:
		evt.type = UDC_RENESAS_RX_EVT_HAL;
		evt.hal_evt = p_args->event;
		k_msgq_put(&drv_msgq, &evt, K_NO_WAIT);
		break;
	}
}

