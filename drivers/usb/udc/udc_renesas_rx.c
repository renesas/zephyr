#define DT_DRV_COMPAT renesas_rx_udc

#define USB_RENESAS_RX_MODULE_NUMBER(id) (DT_REG_ADDR(id) == R_USB_FS0_BASE ? 0 : 1)

#define USB_RENESAS_RX_IRQ_GET(id, name, cell)                                                     \
	COND_CODE_1(DT_IRQ_HAS_NAME(id, name), (DT_IRQ_BY_NAME(id, name, cell)),                   \
		    ((IRQn_Type) BSP_IRQ_DISABLED))

#define USB_RENESAS_RX_MAX_SPEED_IDX(id)                                                           \
	(DT_NODE_HAS_COMPAT(id, renesas_rx_usbhs) ? UDC_BUS_SPEED_HS : UDC_BUS_SPEED_FS)

#define USB_RENESAS_RX_SPEED_IDX(id)                                                               \
	COND_CODE_1(CONFIG_UDC_DRIVER_HIGH_SPEED_SUPPORT_ENABLED,                                  \
			(DT_NODE_HAS_COMPAT(id, renesas_rx_usbhs)                                  \
			? DT_ENUM_IDX_OR(id, maximum_speed, UDC_BUS_SPEED_HS)                      \
			: DT_ENUM_IDX_OR(id, maximum_speed, UDC_BUS_SPEED_FS)),                    \
			(UDC_BUS_SPEED_FS))

#define USB_RENESAS_RX_IRQ_CONNECT(n)                                                              \
	COND_CODE_1(DT_NODE_HAS_COMPAT(DT_INST_PARENT(n), renesas_rx_usbhs),                       \
		    (                                                                              \
			IRQ_CONNECT(DT_IRQ_BY_NAME(DT_INST_PARENT(n), usbhsr, irq),                \
				    DT_IRQ_BY_NAME(DT_INST_PARENT(n), usbhsr, priority),           \
				    udc_renesas_rx_interrupt_handler, DEVICE_DT_INST_GET(n), 0);   \
		    ),                                                                             \
		    (                                                                              \
			int usbi_irq = DT_IRQ_BY_NAME(DT_INST_PARENT(n), usbi, irq);               \
                                                                                                   \
			if (usbi_irq >= 128 && usbi_irq < 144) {                                   \
				R_ICU->SLIXR[usbi_irq - 128].SLIXR = ICU_EVENT_USB0_STATUS;        \
			} else if (usbi_irq >= 144) {                                              \
				R_ICU->SLIR[usbi_irq - 144].SLIR = ICU_EVENT_USB0_STATUS;          \
			}                                                                          \
                                                                                                   \
			IRQ_CONNECT(DT_IRQ_BY_NAME(DT_INST_PARENT(n), usbi, irq),                  \
				DT_IRQ_BY_NAME(DT_INST_PARENT(n), usbi, priority),                 \
				udc_renesas_rx_usbi_interrupt_handler, DEVICE_DT_INST_GET(n), 0);  \
			IRQ_CONNECT(DT_IRQ_BY_NAME(DT_INST_PARENT(n), usbr, irq),                  \
				DT_IRQ_BY_NAME(DT_INST_PARENT(n), usbr, priority),                 \
				udc_renesas_rx_usbr_interrupt_handler, DEVICE_DT_INST_GET(n), 0);  \
		    )                                                                              \
		   )

#define USB_RENESAS_RX_CLOCKS_GET(idx, id)                                                         \
	DEVICE_DT_GET_OR_NULL(DT_PHANDLE_BY_IDX(id, phys_clock, idx))

#define USB_RENESAS_RX_CLOCKS_DEV(n)                                                               \
	LISTIFY(DT_PROP_LEN_OR(DT_INST_PARENT(n), phys_clock, 0),                                  \
			USB_RENESAS_RX_CLOCKS_GET, (,), DT_INST_PARENT(n))

#define UDC_RENESAS_RX_DEVICE_DEFINE(n)                                                            \
	PINCTRL_DT_DEFINE(DT_INST_PARENT(n));                                                      \
	K_THREAD_STACK_DEFINE(udc_renesas_rx_stack_##n, CONFIG_UDC_RENESAS_RX_STACK_SIZE);         \
                                                                                                   \
	static const struct device *udc_renesas_rx_clock_dev_##n[] = {                             \
		USB_RENESAS_RX_CLOCKS_DEV(n)};                                                     \
                                                                                                   \
	static void udc_renesas_rx_thread_##n(void *dev, void *arg1, void *arg2)                   \
	{                                                                                          \
		renesas_rx_thread_handler(dev);                                                    \
	}                                                                                          \
                                                                                                   \
	static void udc_renesas_rx_make_thread_##n(const struct device *dev)                       \
	{                                                                                          \
		struct udc_renesas_rx_data *priv = udc_get_private(dev);                           \
                                                                                                   \
		k_thread_create(&priv->thread_data, udc_renesas_rx_stack_##n,                      \
				K_THREAD_STACK_SIZEOF(udc_renesas_rx_stack_##n),                   \
				udc_renesas_rx_thread_##n, (void *)dev, NULL, NULL,                \
				K_PRIO_COOP(CONFIG_UDC_RENESAS_RX_THREAD_PRIORITY), K_ESSENTIAL,   \
				K_NO_WAIT);                                                        \
		k_thread_name_set(&priv->thread_data, dev->name);                                  \
	}                                                                                          \
                                                                                                   \
	static struct udc_ep_config ep_cfg_in##n[DT_PROP(DT_INST_PARENT(n), num_bidir_endpoints)]; \
	static struct udc_ep_config                                                                \
		ep_cfg_out##n[DT_PROP(DT_INST_PARENT(n), num_bidir_endpoints)];                    \
                                                                                                   \
	static const struct udc_renesas_rx_config udc_renesas_rx_config_##n = {                    \
		.pcfg = PINCTRL_DT_DEV_CONFIG_GET(DT_INST_PARENT(n)),                              \
		.clocks = udc_renesas_rx_clock_dev_##n,                                            \
		.num_of_clocks = DT_PROP_LEN_OR(DT_INST_PARENT(n), phys_clock, 0),                 \
		.num_of_eps = DT_PROP(DT_INST_PARENT(n), num_bidir_endpoints),                     \
		.ep_cfg_in = ep_cfg_in##n,                                                         \
		.ep_cfg_out = ep_cfg_out##n,                                                       \
		.make_thread = udc_renesas_rx_make_thread_##n,                                     \
		.speed_idx = USB_RENESAS_RX_MAX_SPEED_IDX(DT_INST_PARENT(n)),                      \
	};                                                                                         \
                                                                                                   \
	static struct udc_renesas_rx_data udc_priv_##n = {                                         \
		.udc_cfg =                                                                         \
			{                                                                          \
				.module_number = USB_RENESAS_RX_MODULE_NUMBER(DT_INST_PARENT(n)),  \
				.usb_speed = USB_RENESAS_RX_SPEED_IDX(DT_INST_PARENT(n)),          \
				.irq = USB_RENESAS_RX_IRQ_GET(DT_INST_PARENT(n), usbi, irq),       \
				.irq_r = USB_RENESAS_RX_IRQ_GET(DT_INST_PARENT(n), usbr, irq),     \
				.hs_irq = USB_RENESAS_RX_IRQ_GET(DT_INST_PARENT(n), usbhsr, irq),  \
				.ipl = USB_RENESAS_RX_IRQ_GET(DT_INST_PARENT(n), usbi, priority),  \
				.ipl_r =                                                           \
					USB_RENESAS_RX_IRQ_GET(DT_INST_PARENT(n), usbr, priority), \
				.hsipl = USB_RENESAS_RX_IRQ_GET(DT_INST_PARENT(n), usbhsr,         \
								priority),                         \
				.p_context = DEVICE_DT_INST_GET(n),                                \
				.p_callback = udc_renesas_rx_event_handler,                        \
			},                                                                         \
	};                                                                                         \
                                                                                                   \
	static struct udc_data udc_data_##n = {                                                    \
		.mutex = Z_MUTEX_INITIALIZER(udc_data_##n.mutex),                                  \
		.priv = &udc_priv_##n,                                                             \
	};                                                                                         \
                                                                                                   \
	int udc_renesas_rx_driver_preinit##n(const struct device *dev)                             \
	{                                                                                          \
		USB_RENESAS_RX_IRQ_CONNECT(n)                                                      \
		return udc_renesas_rx_driver_preinit(dev);                                         \
	}                                                                                          \
                                                                                                   \
	DEVICE_DT_INST_DEFINE(n, udc_renesas_rx_driver_preinit##n, NULL, &udc_data_##n,            \
			      &udc_renesas_rx_config_##n, POST_KERNEL,                             \
			      CONFIG_KERNEL_INIT_PRIORITY_DEVICE, &udc_renesas_rx_api);

