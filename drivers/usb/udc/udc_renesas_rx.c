static int udc_renesas_rx_test_mode(const struct device *dev, const uint8_t mode, const bool dryrun)
{
	struct udc_renesas_rx_data *data = udc_get_private(dev);
	usbd_test_mode_t hal_test_mode;
	int err;

	switch (mode) {
	case USB_SFS_TEST_MODE_J:
		hal_test_mode = USBD_TEST_MODE_J;
		break;
	case USB_SFS_TEST_MODE_K:
		hal_test_mode = USBD_TEST_MODE_K;
		break;
	case USB_SFS_TEST_MODE_SE0_NAK:
		hal_test_mode = USBD_TEST_MODE_SE0_NAK;
		break;
	case USB_SFS_TEST_MODE_PACKET:
		hal_test_mode = USBD_TEST_MODE_PACKET;
		break;
	default:
		LOG_ERR("Unsupported test mode %u", mode);
		return -EINVAL;
	}

	if (dryrun) {
		LOG_DBG("Test Mode %u supported", mode);
		return 0;
	}

	err = R_USBD_Testmode(&data->udc, hal_test_mode);
	if (err == FSP_ERR_UNSUPPORTED) {
		LOG_ERR("Test mode is not supported in this device");
		return -ENOTSUP;
	}
	if (err != FSP_SUCCESS) {
		LOG_ERR("Failed to set test mode %u", mode);
		return -EIO;
	}

	return 0;
}

