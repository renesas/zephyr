"""Sign / key helper for the OSPI image: ML-DSA-87 (FIPS 204, pure mode).

Re-uses MCUboot's imgtool key handling so the OSPI key has exactly the same
format as the MCUboot key (PKCS#8 PEM holding the 32-byte seed). Needs the
`dilithium-py` package, like imgtool does for ML-DSA.
"""

import argparse
import sys
from pathlib import Path


def _imgtool_keys(mcuboot_scripts):
    sys.path.insert(0, str(Path(mcuboot_scripts)))
    from imgtool.keys.mldsa87 import Mldsa87, load_mldsa87_pem
    return Mldsa87, load_mldsa87_pem


def load_key(a):
    _, load = _imgtool_keys(a.mcuboot_scripts)
    return load(Path(a.key).read_text())


def cmd_genkey(a):
    mldsa87, _ = _imgtool_keys(a.mcuboot_scripts)
    mldsa87.generate().export_private(a.key)


def cmd_header(a):
    pub = load_key(a).get_public_bytes()
    body = ",\n".join(", ".join(f"0x{b:02x}" for b in pub[i:i + 16])
                      for i in range(0, len(pub), 16))
    Path(a.out).write_text(
        "/* Generated by ospi_sign.py - do not edit */\n"
        "#include <stdint.h>\n"
        f"#define OSPI_PUBKEY_LEN {len(pub)}\n"
        f"static const uint8_t ospi_pubkey[OSPI_PUBKEY_LEN] = {{\n{body}\n}};\n")


def cmd_sign(a):
    sig = load_key(a).sign(Path(a.input).read_bytes())
    Path(a.out).write_bytes(sig)


p = argparse.ArgumentParser()
p.add_argument("--mcuboot-scripts", required=True, help="bootloader/mcuboot/scripts")
sub = p.add_subparsers(required=True)
for name, fn, args in (("genkey", cmd_genkey, ["key"]),
                       ("header", cmd_header, ["key", "out"]),
                       ("sign", cmd_sign, ["key", "input", "out"])):
    sp = sub.add_parser(name)
    for arg in args:
        sp.add_argument(arg)
    sp.set_defaults(fn=fn)
a = p.parse_args()
a.fn(a)
